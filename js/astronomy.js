const DEG = Math.PI / 180;
const RAD = 180 / Math.PI;

function julianDate(date) {
  return date.getTime() / 86400000 + 2440587.5;
}

function gstHours(jd) {
  const t = (jd - 2451545.0) / 36525;
  let gst =
    280.46061837 +
    360.98564736629 * (jd - 2451545.0) +
    0.000387933 * t * t -
    (t * t * t) / 38710000;
  gst = ((gst % 360) + 360) % 360;
  return gst / 15;
}

function lstHours(gst, lonDeg) {
  let lst = gst + lonDeg / 15;
  return ((lst % 24) + 24) % 24;
}

function raDecToAltAz(raHours, decDeg, latDeg, lst) {
  const ha = (lst - raHours) * 15 * DEG;
  const dec = decDeg * DEG;
  const lat = latDeg * DEG;
  const sinAlt =
    Math.sin(dec) * Math.sin(lat) + Math.cos(dec) * Math.cos(lat) * Math.cos(ha);
  const alt = Math.asin(Math.min(1, Math.max(-1, sinAlt)));
  const az = Math.atan2(
    -Math.sin(ha),
    Math.tan(dec) * Math.cos(lat) - Math.sin(lat) * Math.cos(ha)
  );
  return { alt: alt * RAD, az: (az * RAD + 360) % 360 };
}

function eclipticToRaDec(lonDeg, latDeg, jd) {
  const t = (jd - 2451545.0) / 36525;
  const eps = (23.439291 - 0.0130042 * t) * DEG;
  const b = latDeg * DEG;
  const l = lonDeg * DEG;
  const sinDec =
    Math.sin(b) * Math.cos(eps) + Math.cos(b) * Math.sin(eps) * Math.sin(l);
  const dec = Math.asin(Math.min(1, Math.max(-1, sinDec)));
  const y = Math.sin(l) * Math.cos(eps) - Math.tan(b) * Math.sin(eps);
  const x = Math.cos(l);
  let ra = Math.atan2(y, x) * RAD;
  ra = ((ra % 360) + 360) % 360;
  return { raHours: ra / 15, decDeg: dec * RAD };
}

function moonPosition(jd) {
  const d = jd - 2451545.0;
  const L = 218.316 + 13.176396 * d;
  const M = 134.963 + 13.064993 * d;
  const F = 93.272 + 13.22935 * d;
  const sun = 280.46 + 0.9856474 * d;
  const lon = L + 6.289 * Math.sin(M * DEG);
  const lat = 5.128 * Math.sin(F * DEG);
  const phase = (1 - Math.cos(((L - sun) % 360) * DEG)) / 2;
  return { ...eclipticToRaDec(lon, lat, jd), phase };
}

function galacticToRaDec(lDeg, bDeg) {
  const l = lDeg * DEG;
  const b = bDeg * DEG;
  const lNCP = 122.932 * DEG;
  const raNGP = 192.85948 * DEG;
  const decNGP = 27.12825 * DEG;
  const sinDec =
    Math.sin(b) * Math.sin(decNGP) +
    Math.cos(b) * Math.cos(decNGP) * Math.cos(lNCP - l);
  const dec = Math.asin(Math.min(1, Math.max(-1, sinDec)));
  const y = Math.cos(b) * Math.sin(lNCP - l);
  const x =
    Math.sin(b) * Math.cos(decNGP) -
    Math.cos(b) * Math.sin(decNGP) * Math.cos(lNCP - l);
  let ra = raNGP - Math.atan2(y, x);
  ra = ((ra % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI);
  return { raHours: (ra * RAD) / 15, decDeg: dec * RAD };
}

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

