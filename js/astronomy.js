function buildCatalog() {
  const rand = mulberry32(20251011);
  const faint = [];
  for (let i = 0; i < 1400; i += 1) {
    const z = rand() * 2 - 1;
    const ra = rand() * 24;
    const dec = Math.asin(z) * RAD;
    const mag = 3.8 + rand() * 2.6;
    faint.push([ra, dec, mag]);
  }
  return BRIGHT_STARS.concat(faint);
}

const STAR_CATALOG = buildCatalog();

